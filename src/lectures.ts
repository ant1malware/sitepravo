function slugify(t: string) {
  return t
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\s-]/gu, "")
    .trim()
    .replace(/\s+/g, "-")
    .slice(0, 80);
}

/**
 * Пытаемся разбить большой текст на логические секции.
 * Ищем заголовки вида:
 *  - строки начинающиеся с "## " (Markdown),
 *  - или "Лекция", "Тема", "Раздел", "Глава", "Инструкция", "Порядок" + далее текст,
 *  - или ПРОСТО ПЕРВАЯ СТРОКА, если ничего не нашли (будет одна карточка).
 */
function splitIntoSections(raw: string): LectureSection[] {
  const text = (raw || "").trim();
  if (!text) return [];

  // Разделяем предварительно по двойным переводам строки — так уменьшаем шанс склейки заголовков
  const blocks = text.split(/\n{2,}/);

  // Собираем секции: заголовок — первая строка блока, тело — остальное
  const sections: LectureSection[] = [];
  let bufTitle: string | null = null;
  let bufBody: string[] = [];

  // функция фиксации накопленной секции
  const flush = () => {
    if (bufTitle || bufBody.length) {
      const title = (bufTitle || "Учебные материалы").trim();
      const body = bufBody.join("\n\n").trim();
      sections.push({
        id: slugify(title) || `sec-${sections.length + 1}`,
        title,
        text: body || title, // если нет тела — пусть хотя бы заголовок будет в тексте
        source:
          "https://forum.amazing-online.com/threads/uchebnye-materialy-dlja-sotrudnikov-pravitelstvennogo-apparata.1065800/",
      });
    }
    bufTitle = null;
    bufBody = [];
  };

  // паттерн строк, которые с высокой вероятностью являются заголовком
  const titleRe =
  /^(##\s+.+|Лекция\s*(на\s+тему)?\s*[:«"].+|Тема[\.:]\s*.+|Раздел[\.:]\s*.+|Глава[\.:]\s*.+|Инструкция[\.:]\s*.+|Порядок[\.:]\s*.+)$/i;

  for (const b of blocks) {
    const trimmed = b.trim();
    if (!trimmed) continue;

    // первая строка блока
    const firstLine = (trimmed.match(/^[^\n]+/) || [""])[0].trim();

    if (titleRe.test(firstLine)) {
      // новый заголовок — сбрасываем предыдущий
      flush();
      // убираем префикс "## "
      const t = firstLine.replace(/^##\s+/, "").trim();
      bufTitle = t;
      // всё, что после первой строки — тело
      const body = trimmed.slice(firstLine.length).trim();
      if (body) bufBody.push(body);
    } else if (!bufTitle && sections.length === 0) {
      // самый первый блок без явного заголовка — считаем его заголовком
      bufTitle = firstLine;
      const body = trimmed.slice(firstLine.length).trim();
      if (body) bufBody.push(body);
    } else {
      // продолжаем тело текущей секции
      bufBody.push(trimmed);
    }
  }
  flush();

  // если вдруг автоматика не распознала — вернём один раздел целиком
  if (sections.length === 0) {
    return [
      {
        id: "lectures",
        title: "Учебные материалы",
        text,
        source:
          "https://forum.amazing-online.com/threads/uchebnye-materialy-dlja-sotrudnikov-pravitelstvennogo-apparata.1065800/",
      },
    ];
  }

  return sections;
}

// ===== готовый массив секций, который будет использовать UI и поиск =====
export const lectures: LectureSection[] = splitIntoSections(LECTURES_RAW);
